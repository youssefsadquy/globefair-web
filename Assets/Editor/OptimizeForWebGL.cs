using UnityEngine;
using UnityEditor;
using System.Text;
using System.Collections.Generic;

// Batch WebGL-platform-override tool, added while fixing "Start Fair" and "Customise Avatar"
// failing to load in the WebGL build. Root cause (diagnosed via a live Editor session +
// browser test): the built WebGLBuild.data archive was ~1.4GB, almost entirely because
// hundreds of source textures under Assets/Exhibition/Models/Textures (and possibly other
// folders) have no WebGL-specific import override, so they ship at full desktop resolution/
// size instead of a browser-appropriate compressed size. That caused the engine to fail
// mid-read on the shared asset data for any scene beyond the initial dashboard (surfaced as
// "Unknown error occurred while loading 'sharedassets1.assets'", and - downstream of that -
// a NullReferenceException in UMA's texture generator when the avatar customiser scene tried
// to build a character).
//
// This does NOT touch any source asset - it only writes per-platform ("WebGL") import
// overrides, which Unity stores in the .meta file and applies purely at build time. The
// original textures/audio on disk, and how they look in the Editor or in non-WebGL builds,
// are untouched. Safe to re-run - it skips anything already at or below the target settings.
public static class OptimizeForWebGL
{
    // Any texture whose current WebGL max size is already <= this is left alone.
    private const int WebGLMaxTextureSize = 1024;

    [MenuItem("Tools/WebGL/1. Optimize All Textures For WebGL")]
    public static void OptimizeTextures()
    {
        string[] guids = AssetDatabase.FindAssets("t:Texture2D");
        var changedLog = new List<string>();
        int changed = 0, alreadyOk = 0, skipped = 0, errors = 0;

        AssetDatabase.StartAssetEditing();
        try
        {
            for (int i = 0; i < guids.Length; i++)
            {
                string path = AssetDatabase.GUIDToAssetPath(guids[i]);

                // Skip editor-only textures (never shipped in the WebGL build anyway) and
                // TextMesh Pro's font atlases (capping those blurs in-game text).
                if (path.Contains("/Editor/") || path.Contains("Editor Default Resources") ||
                    path.Contains("/TextMesh Pro/"))
                {
                    skipped++;
                    continue;
                }

                var importer = AssetImporter.GetAtPath(path) as TextureImporter;
                if (importer == null) { skipped++; continue; }

                // Lightmaps are regenerated by the Lighting bake, not something to hand-tune here.
                if (importer.textureType == TextureImporterType.Lightmap) { skipped++; continue; }

                var platformSettings = importer.GetPlatformTextureSettings("WebGL");
                bool dirty = false;

                if (!platformSettings.overridden) { platformSettings.overridden = true; dirty = true; }
                if (platformSettings.maxTextureSize > WebGLMaxTextureSize)
                {
                    platformSettings.maxTextureSize = WebGLMaxTextureSize;
                    dirty = true;
                }
                else if (!platformSettings.overridden)
                {
                    platformSettings.maxTextureSize = WebGLMaxTextureSize;
                }
                if (platformSettings.format != TextureImporterFormat.Automatic)
                {
                    platformSettings.format = TextureImporterFormat.Automatic;
                    dirty = true;
                }
                if (platformSettings.textureCompression != TextureImporterCompression.Compressed)
                {
                    platformSettings.textureCompression = TextureImporterCompression.Compressed;
                    dirty = true;
                }

                if (dirty)
                {
                    importer.SetPlatformTextureSettings(platformSettings);
                    EditorUtility.SetDirty(importer);
                    try
                    {
                        importer.SaveAndReimport();
                        changed++;
                        changedLog.Add(path);
                    }
                    catch (System.Exception e)
                    {
                        errors++;
                        changedLog.Add("ERROR reimporting " + path + ": " + e.Message);
                    }
                }
                else
                {
                    alreadyOk++;
                }
            }
        }
        finally
        {
            AssetDatabase.StopAssetEditing();
        }

        var sb = new StringBuilder();
        sb.AppendLine("=== WebGL Texture Optimization Complete ===");
        sb.AppendLine(string.Format("Scanned: {0}  Changed: {1}  Already OK: {2}  Skipped: {3}  Errors: {4}",
            guids.Length, changed, alreadyOk, skipped, errors));
        foreach (var line in changedLog) sb.AppendLine(line);
        Debug.Log(sb.ToString());

        AssetDatabase.SaveAssets();
        AssetDatabase.Refresh();
    }

    [MenuItem("Tools/WebGL/2. Compress All Audio For WebGL")]
    public static void OptimizeAudio()
    {
        string[] guids = AssetDatabase.FindAssets("t:AudioClip");
        var changedLog = new List<string>();
        int changed = 0, alreadyOk = 0, skipped = 0, errors = 0;

        AssetDatabase.StartAssetEditing();
        try
        {
            for (int i = 0; i < guids.Length; i++)
            {
                string path = AssetDatabase.GUIDToAssetPath(guids[i]);
                if (path.Contains("/Editor/")) { skipped++; continue; }

                var importer = AssetImporter.GetAtPath(path) as AudioImporter;
                if (importer == null) { skipped++; continue; }

                var platformSettings = importer.GetOverrideSampleSettings("WebGL");
                bool dirty = false;

                if (!importer.ContainsSampleSettingsOverride("WebGL"))
                {
                    dirty = true;
                }
                if (platformSettings.loadType != AudioClipLoadType.CompressedInMemory)
                {
                    platformSettings.loadType = AudioClipLoadType.CompressedInMemory;
                    dirty = true;
                }
                if (platformSettings.compressionFormat != AudioCompressionFormat.Vorbis)
                {
                    platformSettings.compressionFormat = AudioCompressionFormat.Vorbis;
                    dirty = true;
                }
                if (platformSettings.quality > 0.5f)
                {
                    platformSettings.quality = 0.5f;
                    dirty = true;
                }

                if (dirty)
                {
                    importer.SetOverrideSampleSettings("WebGL", platformSettings);
                    EditorUtility.SetDirty(importer);
                    try
                    {
                        importer.SaveAndReimport();
                        changed++;
                        changedLog.Add(path);
                    }
                    catch (System.Exception e)
                    {
                        errors++;
                        changedLog.Add("ERROR reimporting " + path + ": " + e.Message);
                    }
                }
                else
                {
                    alreadyOk++;
                }
            }
        }
        finally
        {
            AssetDatabase.StopAssetEditing();
        }

        var sb = new StringBuilder();
        sb.AppendLine("=== WebGL Audio Optimization Complete ===");
        sb.AppendLine(string.Format("Scanned: {0}  Changed: {1}  Already OK: {2}  Skipped: {3}  Errors: {4}",
            guids.Length, changed, alreadyOk, skipped, errors));
        foreach (var line in changedLog) sb.AppendLine(line);
        Debug.Log(sb.ToString());

        AssetDatabase.SaveAssets();
        AssetDatabase.Refresh();
    }

    // Reports the current total on-disk size of everything Unity would package for WebGL
    // (Texture2D + AudioClip + Mesh source assets), so we have a before/after number without
    // needing a full build. Not exact (final .data size also depends on compression + IL2CPP
    // overhead) but tracks the win/loss of the two passes above directionally.
    [MenuItem("Tools/WebGL/3. Report Asset Size Summary")]
    public static void ReportSizes()
    {
        ReportForType("t:Texture2D", "Textures");
        ReportForType("t:AudioClip", "Audio");
        ReportForType("t:Mesh", "Meshes/Models");
    }

    private static void ReportForType(string filter, string label)
    {
        string[] guids = AssetDatabase.FindAssets(filter);
        long total = 0;
        int count = 0;
        foreach (var guid in guids)
        {
            string path = AssetDatabase.GUIDToAssetPath(guid);
            string fullPath = System.IO.Path.Combine(System.IO.Directory.GetCurrentDirectory(), path);
            if (System.IO.File.Exists(fullPath))
            {
                total += new System.IO.FileInfo(fullPath).Length;
                count++;
            }
        }
        Debug.Log(string.Format("[Asset Size Report] {0}: {1} files, {2:N1} MB on disk (source, pre-compression)",
            label, count, total / (1024.0 * 1024.0)));
    }
}
